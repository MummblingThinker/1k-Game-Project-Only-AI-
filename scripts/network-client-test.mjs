import assert from 'node:assert/strict';
import { NetworkClient } from '../public/js/network.js';

// A late packet must not pull a player back into a room they just left.
const handlers = new Map();
const sent = [];
const states = [];
const reports = [];
const socket = { on: (event, handler) => handlers.set(event, handler), emit: (...args) => sent.push(args) };
globalThis.window = { io: () => socket };
try {
  const client = new NetworkClient({ onState: (state) => states.push(state),onDiagnostics:r=>reports.push(r) });
  const connecting = client.ensureConnected();
  handlers.get('connect')();
  assert.equal(await connecting, true);
  const state = { roomCode: 'ABC234', runId:1, players: [{ id: 'one' }], phase: 'playing' };
  handlers.get('roomJoined')({ roomCode: state.roomCode, playerId: 'one', playerCount: 1, state });
  assert.equal(client.inRoom, true);
  client.latestState={...state,phase:'victory'};client.nextLevel();assert.equal(sent.at(-1)[0],'nextLevel');
  client.latestState={...state,phase:'cutscene'};client.nextLevel();assert.equal(sent.at(-1)[0],'skipStory');
  client.latestState=state;const actions=sent.length;client.nextLevel();assert.equal(sent.length,actions,'playing cannot advance');
  handlers.get('roomState')({ ...state, roomCode: 'XYZ567' });
  assert.equal(states.length, 1, 'foreign-room packet must be ignored');
  handlers.get('diagnostics')({roomCode:'XYZ567',runId:1,report:{stage:1}});
  handlers.get('diagnostics')({roomCode:'ABC234',runId:0,report:{stage:1}});
  assert.equal(reports.length,0,'foreign and previous-run reports ignored');
  client.requestDiagnostics();assert.equal(sent.at(-1)[0],'getDiagnostics');
  handlers.get('diagnostics')({roomCode:'ABC234',runId:1,report:{stage:2}});
  assert.deepEqual(reports,[{stage:2}]);
  handlers.get('roomState')({ ...state, players: [{id:'two', x:900}, {id:'one', x:12}] });
  assert.equal(client.latestState.playerId, 'one');
  assert.equal(client.latestState.you.x, 12, 'shared packet selects own survivor, not first player');
  assert.equal(client.latestState.players.length, 2);
  client.leaveRoom();
  assert.equal(states.at(-1), null);
  const count = states.length;
  handlers.get('roomState')(state);
  assert.equal(states.length, count, 'late room packet must not resurrect a departed session');
  assert.equal(client.inRoom, false);
  handlers.get('diagnostics')({roomCode:'ABC234',runId:1,report:{stage:2}});
  assert.equal(reports.length,1,'late report cannot restore left room');
  assert.equal(sent.at(-1)[0], 'leaveRoom');
  handlers.get('disconnect')();
  assert.equal(client.roomCode, null);
  assert.equal(client.playerId, null);
  console.log('Network client PASS: foreign/late room packets ignored; leave/disconnect clear membership.');
} finally { delete globalThis.window; }

const { SnapshotInterpolator } = await import('../public/js/interpolation.js');
const visual = new SnapshotInterpolator();
const packet = (x, extra={}) => ({ roomCode:'ABC234',runId:1,phase:'playing',players:[{id:'p',x,y:129,alive:true,...extra}] });
visual.push(packet(0),0); visual.push(packet(4),50);
assert.equal(visual.sample(75).get('p').x,2);
assert.equal(visual.sample(500).get('p').x,4,'no extrapolation after a stalled connection');
visual.push(packet(12),150); assert.equal(visual.sample(200).get('p').x,8);
visual.push(packet(16),200); assert.equal(visual.sample(200).get('p').x,8,'late packet starts from current visual location');
assert.equal(visual.sample(250).get('p').x,16);
visual.push(packet(20,{alive:false}),250); assert.equal(visual.sample(250).get('p').x,20,'death snaps immediately');
visual.push({...packet(27),runId:2},300); assert.equal(visual.sample(300).get('p').x,27,'new run clears old interpolation');
visual.push(packet(400),350); assert.equal(visual.sample(350).get('p').x,400,'teleport/checkpoint snaps');
visual.clear(); assert.equal(visual.sample(400).size,0);
console.log('Visual interpolation PASS: jittered packets blend, stalls freeze, death/run/teleport reset, authority unchanged.');
